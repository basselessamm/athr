import 'dart:io';

void main() {
  final List<String> quran = [
    '﴿فَإِنَّ مَعَ الْعُسْرِ يُسْرًا﴾',
    '﴿لَا تَحْزَنْ إِنَّ اللَّهَ مَعَنَا﴾',
    '﴿وَاصْبِرْ وَمَا صَبْرُكَ إِلَّا بِاللَّهِ﴾',
    '﴿وَهُوَ مَعَكُمْ أَيْنَ مَا كُنتُمْ﴾',
    '﴿وَرَحْمَتِي وَسِعَتْ كُلَّ شَيْءٍ﴾',
    '﴿فَاسْتَجَبْنَا لَهُ وَنَجَّيْنَاهُ مِنَ الْغَمِّ﴾',
    '﴿وَاللَّهُ يَعْصِمُكَ مِنَ النَّاسِ﴾',
    '﴿إِنَّ اللَّهَ بِمَا تَعْمَلُونَ بَصِيرٌ﴾',
    '﴿وَمَن يَتَوَكَّلْ عَلَى اللَّهِ فَهُوَ حَسْبُهُ﴾',
    '﴿سَيَجْعَلُ اللَّهُ بَعْدَ عُسْرٍ يُسْرًا﴾',
    '﴿وَلَسَوْفَ يُعْطِيكَ رَبُّكَ فَتَرْضَى﴾',
    '﴿ادْعُونِي أَسْتَجِبْ لَكُمْ﴾',
    '﴿وَإِذَا سَأَلَكَ عِبَادِي عَنِّي فَإِنِّي قَرِيبٌ﴾',
    '﴿وَنَحْنُ أَقْرَبُ إِلَيْهِ مِنْ حَبْلِ الْوَرِيدِ﴾',
    '﴿وَاصْبِرْ لِحُكْمِ رَبِّكَ فَإِنَّكَ بِأَعْيُنِنَا﴾'
  ];

  final List<String> hadith = [
    '«عجباً لأمر المؤمن، إن أمره كله خير»',
    '«من يُرد الله به خيراً يُصب منه»',
    '«اتق الله حيثما كنت»',
    '«تبسمك في وجه أخيك صدقة»',
    '«الكلمة الطيبة صدقة»',
    '«خيركم من تعلم القرآن وعلمه»',
    '«لا تغضب، ولك الجنة»',
    '«يسروا ولا تعسروا، وبشروا ولا تنفروا»',
    '«من سلك طريقاً يلتمس فيه علماً سهل الله له به طريقاً إلى الجنة»',
    '«أحب الأعمال إلى الله أدومها وإن قل»',
    '«احفظ الله يحفظك»',
    '«إنما الأعمال بالنيات»',
    '«الدين النصيحة»',
    '«لا يؤمن أحدكم حتى يحب لأخيه ما يحب لنفسه»',
    '«من حسن إسلام المرء تركه ما لا يعنيه»'
  ];

  final List<String> athr = [
    'لا تيأس، فخزائن الله أوسع من أحلامك.',
    'كلما ضاقت، تذكر أن الله قريب.',
    'صلاتك هي النور الذي يضيء عتمة أيامك.',
    'الاستغفار يفتح الأقفال، فأكثر منه.',
    'كن أثراً طيباً، فالعمر قصير.',
    'من جعل سعادته في رضا الله، سعدت حياته.',
    'لا تحمل هم الغد، فمُدبّر الأمر هو الله.',
    'اصنع خيراً دعه سراً، فنور الأسرار لا ينطفئ.',
    'التفاؤل بالخير هو نصف الطريق للنجاح.',
    'سامح واعفُ، فالله يحب العافين عن الناس.',
    'اجعل لك خبيئة من عمل صالح لا يعلمها إلا الله.',
    'أعظم الطمأنينة أن تفوض أمرك لله.',
    'بادر بالخير، فربما ابتسامة منك أحيت قلباً.',
    'في كل محنة منحة، فقط أحسن الظن بالله.',
    'الرضا بقضاء الله يزرع في القلب جنة.'
  ];

  final List<String> allMessages = [];
  int qIndex = 0;
  int hIndex = 0;
  int aIndex = 0;

  for (int i = 0; i < 365; i++) {
    if (i % 3 == 0) {
      allMessages.add(quran[qIndex % quran.length]);
      qIndex++;
    } else if (i % 3 == 1) {
      allMessages.add(hadith[hIndex % hadith.length]);
      hIndex++;
    } else {
      allMessages.add(athr[aIndex % athr.length]);
      aIndex++;
    }
  }

  final file = File('lib/core/notifications/daily_messages.dart');
  final listStr = allMessages.map((m) => "'\$m'").join(',\\n  ');
  file.writeAsStringSync('''
const List<String> dailyMessages = [
  \$listStr
];
''');
}
